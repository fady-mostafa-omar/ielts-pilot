const DICTS: Record<Lang, Record<Key, string>> = { ar, en };

export type T = (key: Key, vars?: Record<string, string | number>) => string;

interface I18n {
  lang: Lang;
  t: T;
  formatDate: (iso: string | null) => string;
  formatShortDate: (iso: string) => string;
  formatBand: (band: number | null | undefined) => string;
  formatHours: (minutes: number) => string;
  formatDays: (n: number) => string;
}

/** "2026-11-03" is a calendar day: read it as local midnight, not UTC. */
function parseDate(iso: string): Date {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(iso);
  return m ? new Date(Number(m[1]), Number(m[2]) - 1, Number(m[3])) : new Date(iso);
}

// Egyptian Arabic counting: ساعة، ساعتين، 3 ساعات … 10 ساعات، 11 ساعة
function arabicHours(minutes: number): string {
  const whole = Math.floor(minutes / 60);
  const half = minutes % 60 >= 30;
  if (whole === 0) return "نص ساعة";
  const base =
    whole === 1 ? "ساعة" : whole === 2 ? "ساعتين" : whole <= 10 ? `${whole} ساعات` : `${whole} ساعة`;
  return half ? `${base} ونص` : base;
}

function arabicDays(n: number): string {
  if (n === 1) return "يوم";
  if (n === 2) return "يومين";
  return n >= 3 && n <= 10 ? `${n} أيام` : `${n} يوم`;
}

function englishHours(minutes: number): string {
  if (minutes < 60) return `${minutes} min`;
  const h = minutes / 60;
  return `${Number.isInteger(h) ? h : h.toFixed(1)} ${h === 1 ? "hour" : "hours"}`;
}

const I18nContext = createContext<I18n | null>(null);

export function I18nProvider({ lang, children }: { lang: Lang; children: ReactNode }) {
  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  }, [lang]);

  const value = useMemo<I18n>(() => {
    const dict = DICTS[lang];
    const locale = lang === "ar" ? "ar-EG-u-nu-latn" : "en-GB";
    const dateFmt = new Intl.DateTimeFormat(locale, {
      day: "numeric",
      month: "long",
      year: "numeric",
    });
    const shortFmt = new Intl.DateTimeFormat(locale, { day: "numeric", month: "short" });
    return {
      lang,
      t: (key, vars) =>
        dict[key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars?.[name] ?? `{${name}}`)),
      formatDate: (iso) => (iso ? dateFmt.format(parseDate(iso)) : "—"),
      formatShortDate: (iso) => shortFmt.format(parseDate(iso)),
      formatBand: (band) => (band === null || band === undefined ? "—" : band.toFixed(1)),
      formatHours: (minutes) => (lang === "ar" ? arabicHours(minutes) : englishHours(minutes)),
      formatDays: (n) => (lang === "ar" ? arabicDays(n) : `${n} ${n === 1 ? "day" : "days"}`),
    };
  }, [lang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18n {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n outside I18nProvider");
  return ctx;
}
